from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env", env_file_encoding="utf-8", extra="ignore"
    )

    bot_token: str
    db_path: Path = Path("data/family.db")

    tz_default: str = "Europe/Moscow"
    digest_time: str = "08:00"
    tick_seconds: int = 60

    # Пороги догонки пропущенного — три ступени в `ticker.lateness`
    late_silent_min: int = 10
    late_summary_hours: int = 12

    # Живая панель дня (этап 2п). Дебаунс склеивает серию правок в одно
    # редактирование; порог — после скольких сообщений панель уехала вверх
    # настолько, что проще выпустить новую, чем править невидимую.
    # Дебаунс дробный намеренно: тест ставит 0.01 и не ждёт секунду на прогон
    panel_max_messages: int = 20
    panel_debounce_seconds: float = 2.0

    # Утренняя уборка чата (этап 11): на сколько message_id назад заглядывать.
    # 0 = уборка выключена — идиома проекта, как `backup_keep` и
    # `llm_daily_limit`. Второй настройки не нужно: это же число служит
    # потолком догонки, когда ПК простоял несколько суток
    sweep_window: int = 1000

    # Ежедневный бэкап (этап 6): сколько копий держать в `data/backups/`.
    # 0 = ежедневный снимок выключен, но `/backup` работает — он в каталог
    # не заглядывает вовсе
    backup_keep: int = 7

    openrouter_key: str = ""
    openrouter_model: str = ""

    # Цепочка моделей, через запятую, в порядке перебора (этап 12). Каждая
    # запись — `вендор:модель`; без префикса подразумевается `openrouter`.
    # Пусто = берём одну `OPENROUTER_MODEL`, как было до этапа 12.
    #
    # Условие, без которого список бесполезен: следующая модель обязана
    # отказывать НЕЗАВИСИМО от предыдущей. 01.09.2026 разбор встал целиком на
    # 401 от GMICloud — единственного провайдера `minimax/minimax-m3:free`;
    # `minimax/minimax-m2.7:free` как запасная бесполезна, провайдер тот же.
    # Разные вендоры (`groq:` и `openrouter:`) дают эту независимость надёжнее,
    # чем разные провайдеры внутри одного OpenRouter
    llm_models: str = ""

    # Groq как вендор разбора (не только расшифровки). Ключ и прокси у аккаунта
    # одни на оба применения, поэтому пустые значения берутся из `STT_*`:
    # заводить вторую строку с тем же секретом — верный способ развести их со
    # временем. Отдельные имена оставлены на случай, если аккаунты разделят
    groq_key: str = ""
    groq_proxy: str = ""

    # Сколько запросов к моделям в сутки себе позволяем — на всю цепочку разом.
    # Считаем сами, по `parse.log`: провайдер о приближении к лимиту не
    # предупреждает, он просто начинает отвечать 429, и разбор молча
    # деградирует до `dateparser`. Упереться в потолок своим счётчиком лучше,
    # чем чужим: свой умеет сказать об этом вслух.
    #
    # 200, а не прежние 45. Сорок пять были подогнаны под 50 запросов в сутки у
    # бесплатного тира OpenRouter без пополнения — но аккаунт кредиты покупал
    # (`is_free_tier: false`, то есть 1000/сутки), а с этапа 12 первым в цепочке
    # стоит Groq, у которого тоже 1000. Тормоз оставлен, но перестал срабатывать
    # раньше настоящих лимитов.
    # 0 = не ограничивать
    llm_daily_limit: int = 200

    # Порог автосохранения разбора без карточки подтверждения (шаг 3b.6).
    # 0 = выключено, и это значение по умолчанию: инвариант «ничего не
    # сохраняется молча» снимается только осознанно, когда по `parse.log`
    # станет видно, что модель на высокой уверенности не ошибается
    autosave_confidence: float = 0.0

    # Расшифровка голосовых (этап 5). Отдельный вендор и отдельный ключ:
    # Whisper-совместимый эндпоинт Groq принимает ogg/opus Telegram как есть,
    # поэтому ffmpeg проекту не нужен, а его суточная квота не пересекается
    # с лимитом OpenRouter, на котором держится текстовый разбор
    stt_key: str = ""
    stt_model: str = "whisper-large-v3-turbo"
    stt_url: str = "https://api.groq.com/openai/v1/audio/transcriptions"

    # Потолок длины голосового и срок жизни приглашения по кнопке «🎤 Голосом»
    voice_max_seconds: int = 120
    voice_window_seconds: int = 300

    # Пустое значение = работаем напрямую, без прокси
    telegram_proxy: str = ""
    openrouter_proxy: str = ""
    stt_proxy: str = ""

    @property
    def db_url(self) -> str:
        return f"sqlite+aiosqlite:///{self.db_path}"


settings = Settings()  # type: ignore[call-arg]
